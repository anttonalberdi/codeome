// Agent kit: installs Codeome's specialist roles, orchestration skills and the
// codeome-agent runtime into a project. Plain Node (no Electron) so it is testable.
//
// Installed layout in the project:
//   .claude/agents/<role>.md           Claude subagents; Codex reads the same files
//   .claude/skills/<skill>/SKILL.md    /orchestrate, /delegate, /cross-review, and the playbooks of the chosen groups
//   .claude/skills/orchestrate/routing.md   generated role → engine table
//   .claude/settings.json              hooks that record Claude subagent jobs (merged)
//   .codeome/bin/codeome-agent         Codex wrapper, job records, hook entry point
//   .codeome/kit.json                  version, groups and hashes of installed files
//   .codeome/agents.json               engine and model chosen per agent in Settings
// Files the user has edited since installation are never overwritten or removed.
//
// General agents live in Codeome's own store. The kit still never writes to a Claude account folder on its own;
// mirrorGeneral writes the Codeome general store into account folders (~/.claude/agents by default), when an agent
// is created or promoted and when the app starts or the accounts change. Settings also lists account agents and
// marks name clashes.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const os = require('os');

const KIT = path.join(__dirname, '..', 'kit');
const MANIFEST = JSON.parse(fs.readFileSync(path.join(KIT, 'manifest.json'), 'utf8'));
const HOOK_CMD = 'python3 "$CLAUDE_PROJECT_DIR/.codeome/bin/codeome-agent" hook';
const PERMISSION = 'Bash(.codeome/bin/codeome-agent *)';
const IGNORE = ['.codeome/jobs/', '.codeome/worktrees/', '.codeome/plans/'];
const ENGINE_LABEL = { claude: 'Claude', codex: 'Codex', cross: 'the other engine' };
const ENGINES = Object.keys(ENGINE_LABEL);
const ROUTING = '.claude/skills/orchestrate/routing.md';
const AGENTS_JSON = '.codeome/agents.json';
const NEW_AGENT_RE = /^[a-z][a-z0-9-]{1,40}$/;
const EXISTING_AGENT_RE = /^[\w.-]+$/;
const TOOL_PRESETS = { 'read-only': 'Read, Grep, Glob, Bash', edits: 'Read, Edit, Write, Grep, Glob', shell: 'Read, Edit, Write, Bash, Grep, Glob' };
const MODEL_RE = /^[\w.:/[\]-]{0,80}$/;
const EFFORTS = { claudeEffort: ['low', 'medium', 'high', 'xhigh', 'max'], codexEffort: ['minimal', 'low', 'medium', 'high', 'xhigh'] };

const sha = (s) => crypto.createHash('sha256').update(s).digest('hex');
const read = (p) => { try { return fs.readFileSync(p, 'utf8'); } catch { return null; } };
const codeomeHome = (home) => path.resolve(home || process.env.CODEOME_HOME || path.join(os.homedir(), '.codeome'));
const exists = (p) => { try { fs.lstatSync(p); return true; } catch (e) { if (e.code === 'ENOENT') return false; throw e; } };
const lstat = (p) => { try { return fs.lstatSync(p); } catch (e) { if (e.code === 'ENOENT') return null; throw e; } };

function parseFrontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!m) return { meta: {}, body: text };
  const meta = {};
  for (const line of m[1].split('\n')) {
    const i = line.indexOf(':');
    if (i > 0) {
      const value = line.slice(i + 1).trim();
      if (value.startsWith('"') && value.endsWith('"')) {
        try { meta[line.slice(0, i).trim()] = JSON.parse(value); continue; } catch {}
      }
      meta[line.slice(0, i).trim()] = value;
    }
  }
  return { meta, body: m[2] };
}

function roles() {
  const dir = path.join(KIT, 'roles');
  const footer = fs.readFileSync(path.join(dir, '_report.md'), 'utf8');
  return fs.readdirSync(dir).filter((f) => f.endsWith('.md') && !f.startsWith('_')).sort().map((f) => {
    const { meta, body } = parseFrontmatter(fs.readFileSync(path.join(dir, f), 'utf8'));
    return { ...meta, body: body.trim() + '\n' + footer };
  });
}

// Claude Code agent file: only the frontmatter keys Claude Code understands.
function agentFile(r) {
  const fm = ['---', `name: ${r.name}`, `description: ${r.description}`];
  if (r.tools) fm.push(`tools: ${r.tools}`);
  if (r.model) fm.push(`model: ${r.model}`);
  if (r.effort) fm.push(`effort: ${r.effort}`);
  return fm.join('\n') + '\n---\n\n' + r.body;
}

const routingRow = (r) => `| \`${r.name}\` | ${ENGINE_LABEL[r.engine] || r.engine} | ${!r.tools || /Edit|Write/.test(r.tools) ? 'writes' : 'read-only'} | ${String(r.description || '').replace(/\|/g, '/').replace(/\s+/g, ' ').trim()} |`;

function routingFile(list) {
  const rows = list.map(routingRow);
  return [
    '# Routing',
    '',
    'Generated by Codeome from the installed roles. Edit the Engine column to change a default for this project; Codeome will then leave this file alone on updates.',
    '',
    '| Role | Engine | Access | Use for |',
    '|---|---|---|---|',
    ...rows,
    '',
    'Engines:',
    '- **Claude** — Agent tool with `subagent_type` set to the role.',
    '- **Codex** — `.codeome/bin/codeome-agent codex --role <role> --title "…"` with the brief on stdin, run in the background. Sandboxed: no network, no SSH.',
    '- **the other engine** — reviewers run on whichever engine did not write the change.',
    '',
    'Override per task when it helps: a Codex role whose job needs the network or the HPC runs on Claude instead. If the user asks for a specific engine, use it.',
    ''
  ].join('\n');
}

// Kit skills. Each SKILL.md names its group; that key is Codeome's, so it is dropped from the installed file.
function skills() {
  const base = path.join(KIT, 'skills');
  return fs.readdirSync(base).filter((d) => fs.statSync(path.join(base, d)).isDirectory()).sort().map((name) => {
    const files = {};
    for (const f of fs.readdirSync(path.join(base, name)).filter((f) => !f.startsWith('.')).sort()) files[f] = fs.readFileSync(path.join(base, name, f), 'utf8');
    const { meta } = parseFrontmatter(files['SKILL.md']);
    files['SKILL.md'] = setFrontmatter(files['SKILL.md'], 'group', '');
    return { name, group: meta.group, description: meta.description || '', files };
  });
}

function skillFiles(groups) {
  const out = {};
  for (const s of skills()) {
    if (!groups.includes(s.group)) continue;
    for (const [f, content] of Object.entries(s.files)) out[`.claude/skills/${s.name}/${f}`] = content;
  }
  return out;
}

function normalizeGroups(groups) {
  const valid = Object.keys(MANIFEST.groups);
  const want = new Set((groups || valid).filter((g) => valid.includes(g)));
  for (const [g, info] of Object.entries(MANIFEST.groups)) if (info.required) want.add(g);
  return valid.filter((g) => want.has(g));
}

// A role with the engine, Claude model and Claude effort chosen for it in Settings.
function applyOverride(r, o = {}) {
  const out = { ...r };
  if (o.engine) out.engine = o.engine;
  if ('claudeModel' in o) { if (o.claudeModel) out.model = o.claudeModel; else delete out.model; }
  if ('claudeEffort' in o) { if (o.claudeEffort) out.effort = o.claudeEffort; else delete out.effort; }
  return out;
}

// Everything the kit would write for these groups: { relPath: content }.
// overrides: .codeome/agents.json roles; custom: the project's own agents with an engine set.
function plan(groups, overrides = {}, custom = []) {
  const chosen = roles().filter((r) => groups.includes(r.group)).map((r) => applyOverride(r, overrides[r.name]));
  const files = { ...skillFiles(groups) };
  for (const r of chosen) files[`.claude/agents/${r.name}.md`] = agentFile(r);
  files[ROUTING] = routingFile([...chosen, ...custom]);
  files['.codeome/bin/codeome-agent'] = fs.readFileSync(path.join(KIT, 'bin', 'codeome-agent'), 'utf8');
  return files;
}

function readState(project) {
  try { return JSON.parse(fs.readFileSync(path.join(project, '.codeome', 'kit.json'), 'utf8')); } catch { return null; }
}

function status(project) {
  const st = readState(project);
  const base = { latest: MANIFEST.version, groups: MANIFEST.groups, roles: roles().map((r) => ({ name: r.name, group: r.group, engine: r.engine, description: r.description })) };
  if (!st) return { ...base, installed: false };
  const modified = Object.entries(st.files || {}).filter(([rel, h]) => { const c = read(path.join(project, rel)); return c !== null && sha(c) !== h; }).map(([rel]) => rel);
  const missing = Object.keys(st.files || {}).filter((rel) => read(path.join(project, rel)) === null);
  return { ...base, installed: true, version: st.version, installedGroups: st.groups, outdated: st.version !== MANIFEST.version, modified, missing, installedAt: st.installedAt };
}

function mergeSettings(project) {
  const p = path.join(project, '.claude', 'settings.json');
  const raw = read(p);
  let s = {};
  if (raw !== null) { try { s = JSON.parse(raw); } catch { return { error: '.claude/settings.json is not valid JSON; hooks were not added.' }; } }
  s.hooks = s.hooks || {};
  const ours = (groups) => (groups || []).some((g) => (g.hooks || []).some((h) => String(h.command || '').includes('codeome-agent')));
  const add = (event, matcher) => {
    s.hooks[event] = s.hooks[event] || [];
    if (!ours(s.hooks[event])) s.hooks[event].push({ ...(matcher ? { matcher } : {}), hooks: [{ type: 'command', command: HOOK_CMD }] });
  };
  add('PreToolUse', 'Agent');
  add('SubagentStart');
  add('SubagentStop');
  s.permissions = s.permissions || {};
  s.permissions.allow = s.permissions.allow || [];
  if (!s.permissions.allow.includes(PERMISSION)) s.permissions.allow.push(PERMISSION);
  const out = JSON.stringify(s, null, 2) + '\n';
  if (out !== raw) { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, out); }
  return {};
}

function mergeGitignore(project) {
  const p = path.join(project, '.gitignore');
  const cur = read(p) || '';
  const have = new Set(cur.split('\n').map((l) => l.trim()));
  const add = IGNORE.filter((l) => !have.has(l));
  if (!add.length) return;
  fs.writeFileSync(p, cur + (cur && !cur.endsWith('\n') ? '\n' : '') + (cur ? '\n' : '') + '# Codeome agent jobs\n' + add.join('\n') + '\n');
}

// Install or update. Returns what happened to each file.
function install(project, opts = {}) {
  if (!project || !fs.existsSync(project)) throw new Error('Project folder not found: ' + project);
  const groups = normalizeGroups(opts.groups);
  const prev = readState(project) || { files: {} };
  const overrides = readOverrides(project);
  const files = plan(groups, overrides, customRouted(project, overrides));
  const r = { written: [], unchanged: [], skipped: [], removed: [], kept: [], groups };
  const record = {};

  for (const [rel, content] of Object.entries(files)) {
    const abs = path.join(project, rel);
    const cur = read(abs);
    const known = prev.files[rel];
    if (cur !== null && cur === content) { r.unchanged.push(rel); record[rel] = sha(content); continue; }
    // Edited by the user since we installed it, or a file we never wrote: leave it.
    if (cur !== null && (!known || sha(cur) !== known)) { r.skipped.push(rel); if (known) record[rel] = known; continue; }
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content);
    if (rel.startsWith('.codeome/bin/')) fs.chmodSync(abs, 0o755);
    r.written.push(rel);
    record[rel] = sha(content);
  }
  // Roles and skills from groups that were deselected, or dropped from the kit.
  for (const [rel, h] of Object.entries(prev.files)) {
    if (rel in files) continue;
    const cur = read(path.join(project, rel));
    if (cur === null) continue;
    if (sha(cur) === h) { fs.unlinkSync(path.join(project, rel)); r.removed.push(rel); } else r.kept.push(rel);
  }

  const st = mergeSettings(project);
  if (st.error) r.warning = st.error;
  mergeGitignore(project);
  fs.mkdirSync(path.join(project, '.codeome'), { recursive: true });
  fs.writeFileSync(path.join(project, '.codeome', 'kit.json'), JSON.stringify({ version: MANIFEST.version, groups, installedAt: new Date().toISOString(), files: record }, null, 2) + '\n');
  return r;
}

// ---------- agents: engine, model and effort per agent ----------
// Every agent in .claude/agents/ (kit roles and the project's own). The engine lives in
// routing.md, which the orchestrator reads; the Claude model and effort in the agent file's
// frontmatter, which Claude Code reads; the Codex model and effort in .codeome/agents.json,
// which codeome-agent reads. agents.json also keeps the choices across kit updates.
function readOverrides(project) {
  try { const j = JSON.parse(fs.readFileSync(path.join(project, AGENTS_JSON), 'utf8')); return j && typeof j.roles === 'object' && j.roles ? j.roles : {}; } catch { return {}; }
}

function writeOverrides(project, rolesMap) {
  const p = path.join(project, AGENTS_JSON);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, JSON.stringify({ version: 1, roles: rolesMap }, null, 2) + '\n');
}

// role → engine key, from the Engine column of routing.md.
function parseRouting(text) {
  const byLabel = Object.fromEntries(Object.entries(ENGINE_LABEL).map(([k, v]) => [v.toLowerCase(), k]));
  const out = {};
  for (const m of String(text || '').matchAll(/^\|\s*`([\w.-]+)`\s*\|\s*([^|]+?)\s*\|/gm)) {
    const k = byLabel[m[2].toLowerCase()];
    if (k) out[m[1]] = k;
  }
  return out;
}

// Set (or add) one role's Engine cell in routing.md, leaving the rest as it is.
function setRoutingEngine(text, row) {
  const lines = text.split('\n');
  const i = lines.findIndex((l) => new RegExp('^\\|\\s*`' + row.name.replace(/[.]/g, '\\.') + '`\\s*\\|').test(l));
  if (i >= 0) {
    const cells = lines[i].split('|');
    cells[2] = ' ' + ENGINE_LABEL[row.engine] + ' ';
    lines[i] = cells.join('|');
  } else {
    let last = -1;
    lines.forEach((l, k) => { if (/^\|\s*`/.test(l)) last = k; });
    if (last < 0) last = lines.findIndex((l) => /^\|[-|]+\|$/.test(l));
    if (last < 0) return text;
    lines.splice(last + 1, 0, routingRow(row));
  }
  return lines.join('\n');
}

// Set, replace or remove one key in a Markdown file's frontmatter.
function setFrontmatter(text, key, value) {
  const m = text.match(/^---\n([\s\S]*?)\n---(\n|$)/);
  const line = `${key}: ${value}`;
  if (!m) return value ? `---\n${line}\n---\n\n` + text : text;
  const lines = m[1].split('\n');
  const i = lines.findIndex((l) => l.startsWith(key + ':'));
  if (i >= 0) { if (value) lines[i] = line; else lines.splice(i, 1); } else if (value) lines.push(line);
  return '---\n' + lines.join('\n') + '\n---' + m[2] + text.slice(m[0].length);
}

const agentPath = (project, name) => path.join(project, '.claude', 'agents', name + '.md');
// The agents and skills in one Claude folder: a project's .claude, or the account's own (global).
const agentNames = (base) => { try { return fs.readdirSync(path.join(base, 'agents')).filter((f) => /^[\w.-]+\.md$/.test(f)).map((f) => f.slice(0, -3)).sort(); } catch { return []; } };
const skillNames = (base) => { try { return fs.readdirSync(path.join(base, 'skills')).filter((d) => /^\w[\w.-]*$/.test(d) && read(path.join(base, 'skills', d, 'SKILL.md')) !== null).sort(); } catch { return []; } };
const skillFilesIn = (dir) => fs.readdirSync(dir).filter((f) => f.endsWith('.md')).sort((a, b) => (b === 'SKILL.md') - (a === 'SKILL.md') || a.localeCompare(b));
const checkPatch = (patch) => {
  for (const k of ['claudeModel', 'codexModel']) if (k in patch && !MODEL_RE.test(String(patch[k] || '').trim())) throw new Error('Not a model name: ' + patch[k]);
  for (const k of Object.keys(EFFORTS)) if (k in patch && patch[k] && !EFFORTS[k].includes(patch[k])) throw new Error('Unknown effort ' + patch[k]);
};
const accessOf = (tools) => (!tools || /Edit|Write/.test(tools) ? 'writes' : 'read-only');

// The project's own agents whose engine was set here: they get a row in routing.md.
function customRouted(project, overrides) {
  const kitNames = new Set(roles().map((r) => r.name));
  return Object.entries(overrides).filter(([n, o]) => !kitNames.has(n) && o.engine).sort().map(([n, o]) => {
    const text = read(agentPath(project, n));
    if (text === null) return null;
    const { meta } = parseFrontmatter(text);
    return { name: n, engine: o.engine, tools: meta.tools || '', description: meta.description || '' };
  }).filter(Boolean);
}

// globalDir: the Claude account's folder; an agent here replaces the global one of the same name.
function agents(project, globalDir) {
  const st = readState(project);
  const global = new Set(globalDir ? agentNames(globalDir) : []);
  const ov = readOverrides(project);
  const kitRoles = new Map(roles().map((r) => [r.name, r]));
  const routed = parseRouting(read(path.join(project, ROUTING)));
  return agentNames(path.join(project, '.claude')).map((name) => {
    const rel = `.claude/agents/${name}.md`;
    const text = read(path.join(project, rel)) || '';
    const { meta } = parseFrontmatter(text);
    const k = kitRoles.get(name);
    const o = ov[name] || {};
    const fromKit = !!(k && st && st.files && rel in st.files);
    return {
      name, file: rel, path: path.join(project, rel), description: meta.description || '',
      kit: fromKit, group: fromKit ? k.group : null,
      engine: routed[name] || o.engine || (fromKit ? k.engine : 'claude'), defaultEngine: fromKit ? k.engine : 'claude',
      claudeModel: meta.model || '', defaultClaudeModel: fromKit ? k.model || '' : '',
      claudeEffort: meta.effort || '', codexModel: o.codexModel || '', codexEffort: o.codexEffort || '', access: accessOf(meta.tools),
      edited: !!(fromKit && sha(text) !== st.files[rel]), replacesGlobal: global.has(name)
    };
  });
}

// patch: { engine?, claudeModel?, claudeEffort?, codexModel?, codexEffort? }. Files the kit wrote and the user has not
// edited stay "unedited" (their recorded hash follows), so kit updates still apply to them.
function setAgent(project, name, patch = {}) {
  if (!/^[\w.-]+$/.test(name || '')) throw new Error('Bad agent name');
  const abs = agentPath(project, name);
  const text = read(abs);
  if (text === null) throw new Error('No agent ' + name + ' in .claude/agents/');
  if ('engine' in patch && !ENGINES.includes(patch.engine)) throw new Error('Unknown engine ' + patch.engine);
  checkPatch(patch);
  const st = readState(project);
  const k = roles().find((r) => r.name === name && st && st.files && `.claude/agents/${name}.md` in st.files);
  const ov = readOverrides(project);
  const o = { ...(ov[name] || {}) };
  if ('engine' in patch) { if (k && patch.engine === k.engine) delete o.engine; else o.engine = patch.engine; }
  if ('claudeModel' in patch) { const v = String(patch.claudeModel || '').trim(); if (k && v === (k.model || '')) delete o.claudeModel; else o.claudeModel = v; }
  if ('claudeEffort' in patch) { const v = patch.claudeEffort || ''; if (k && v === (k.effort || '')) delete o.claudeEffort; else o.claudeEffort = v; }
  if ('codexModel' in patch) { const v = String(patch.codexModel || '').trim(); if (v) o.codexModel = v; else delete o.codexModel; }
  if ('codexEffort' in patch) { if (patch.codexEffort) o.codexEffort = patch.codexEffort; else delete o.codexEffort; }
  if (Object.keys(o).length) ov[name] = o; else delete ov[name];
  writeOverrides(project, ov);

  const write = (rel, before, after) => {
    if (after === before) return;
    fs.writeFileSync(path.join(project, rel), after);
    if (st && st.files && st.files[rel] && sha(before) === st.files[rel]) st.files[rel] = sha(after);
  };
  const { meta } = parseFrontmatter(text);
  let next = text;
  if ('claudeModel' in patch) next = setFrontmatter(next, 'model', String(patch.claudeModel || '').trim());
  if ('claudeEffort' in patch) next = setFrontmatter(next, 'effort', patch.claudeEffort || '');
  write(`.claude/agents/${name}.md`, text, next);
  if ('engine' in patch) {
    const cur = read(path.join(project, ROUTING));
    if (cur !== null) write(ROUTING, cur, setRoutingEngine(cur, { name, engine: patch.engine, tools: meta.tools || '', description: meta.description || '' }));
  }
  if (st) fs.writeFileSync(path.join(project, '.codeome', 'kit.json'), JSON.stringify(st, null, 2) + '\n');
  return agents(project).find((a) => a.name === name);
}

// New agents belong to a project or to Codeome's general store. Account folders are only written by mirrorGeneral.
function createAgent({ scope, project, name, description, engine, tools, body, home } = {}) {
  if (scope !== 'project' && scope !== 'general') return { error: 'Unknown agent scope' };
  if (!NEW_AGENT_RE.test(name || '')) return { error: 'Bad agent name' };
  if (roles().some((r) => r.name === name)) return { error: 'Kit role names are reserved' };
  if (!['claude', 'codex'].includes(engine)) return { error: 'Unknown engine ' + engine };
  if (!(tools in TOOL_PRESETS)) return { error: 'Unknown tools preset ' + tools };
  if (scope === 'project' && (!project || !fs.existsSync(project))) return { error: 'Project folder not found: ' + project };
  const base = scope === 'general' ? path.join(codeomeHome(home), 'agents') : path.join(project, '.claude', 'agents');
  const p = path.join(base, name + '.md');
  try {
    if (exists(p)) return { error: 'Agent already exists: ' + p };
    const desc = String(description || '').replace(/\s+/g, ' ').trim();
    const content = body && String(body).trim()
      ? String(body).trim()
      : `You are the ${name}: ${desc.replace(/\.$/, '') || 'a specialist agent'}.\n\n## How to work\n- Follow the task brief and report your result.`;
    const footer = fs.readFileSync(path.join(KIT, 'roles', '_report.md'), 'utf8');
    let file = agentFile({ name, description: JSON.stringify(desc), tools: TOOL_PRESETS[tools], body: content + '\n' + footer });
    if (scope === 'general') file = setFrontmatter(file, 'codeome-engine', engine);
    fs.mkdirSync(base, { recursive: true });
    fs.writeFileSync(p, file, { flag: 'wx' });
    if (scope === 'project') {
      setAgent(project, name, { engine });
      const route = path.join(project, ROUTING);
      if (read(route) === null) {
        fs.mkdirSync(path.dirname(route), { recursive: true });
        fs.writeFileSync(route, routingFile(customRouted(project, readOverrides(project))));
      }
    }
    return { path: p };
  } catch (e) { return { error: e.message }; }
}

function promoteAgent({ project, name, toGeneral = false, toProjects = [], home, accountDirs = [] } = {}) {
  const result = { projects: {} };
  const targets = Array.isArray(toProjects) ? toProjects : [];
  const error = !EXISTING_AGENT_RE.test(name || '') ? 'Bad agent name' : !project ? 'Project folder not found: ' + project : null;
  const source = !error && agentPath(project, name);
  const sourceText = source && read(source);
  const problem = error || (sourceText === null ? 'No agent ' + name + ' in .claude/agents/' : null);
  if (problem) {
    if (toGeneral) result.general = { error: problem };
    for (const dest of targets) result.projects[dest] = { error: problem };
    return result;
  }
  const { meta } = parseFrontmatter(sourceText);
  const engine = parseRouting(read(path.join(project, ROUTING)))[name] || (readOverrides(project)[name] || {}).engine || meta['codeome-engine'] || 'claude';
  if (toGeneral) {
    const target = path.join(codeomeHome(home), 'agents', name + '.md');
    try {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.copyFileSync(source, target, fs.constants.COPYFILE_EXCL);
      // The engine choice lives in routing.md / agents.json for a project, so carry it in the file itself.
      if (engine === 'codex' && !meta['codeome-engine']) fs.writeFileSync(target, setFrontmatter(sourceText, 'codeome-engine', 'codex'));
      result.general = 'created';
    } catch (e) { result.general = e.code === 'EEXIST' ? 'exists' : { error: e.message }; }
    if (accountDirs.length && (result.general === 'created' || result.general === 'exists')) {
      try { mirrorGeneral({ home, accountDirs }); } catch (e) { result.general = { error: e.message }; }
    }
  }
  for (const dest of targets) {
    try {
      const projectEntry = lstat(dest);
      if (!projectEntry || !projectEntry.isDirectory()) throw new Error('Project folder not found: ' + dest);
      const projectReal = fs.realpathSync(dest);
      for (const part of ['.claude', path.join('.claude', 'agents')]) {
        const entry = path.join(dest, part);
        if (!exists(entry)) continue;
        const relative = path.relative(projectReal, fs.realpathSync(entry));
        if (relative === '..' || relative.startsWith('..' + path.sep) || path.isAbsolute(relative)) throw new Error('Agent directory leaves project: ' + entry);
      }
      const target = agentPath(dest, name);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.copyFileSync(source, target, fs.constants.COPYFILE_EXCL);
      result.projects[dest] = 'created';
      const route = path.join(dest, ROUTING);
      const before = read(route);
      if (before !== null) fs.writeFileSync(route, setRoutingEngine(before, { name, engine, tools: meta.tools || '', description: meta.description || '' }));
      else if (engine !== 'claude') writeOverrides(dest, { ...readOverrides(dest), [name]: { engine } });
    } catch (e) { result.projects[dest] = e.code === 'EEXIST' ? 'exists' : { error: e.message }; }
  }
  return result;
}

