// Agent kit: installs Codeome's specialist roles, orchestration skills and the
// codeome-agent runtime into a project. Plain Node (no Electron) so it is testable.
//
// Installed layout in the project:
//   .claude/agents/<role>.md           Claude subagents; Codex reads the same files
//   .claude/skills/<skill>/SKILL.md    /orchestrate, /delegate, /cross-review
//   .claude/skills/orchestrate/routing.md   generated role → engine table
//   .claude/settings.json              hooks that record Claude subagent jobs (merged)
//   .codeome/bin/codeome-agent         Codex wrapper, job records, hook entry point
//   .codeome/kit.json                  version, groups and hashes of installed files
// Files the user has edited since installation are never overwritten or removed.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const KIT = path.join(__dirname, '..', 'kit');
const MANIFEST = JSON.parse(fs.readFileSync(path.join(KIT, 'manifest.json'), 'utf8'));
const HOOK_CMD = 'python3 "$CLAUDE_PROJECT_DIR/.codeome/bin/codeome-agent" hook';
const PERMISSION = 'Bash(.codeome/bin/codeome-agent *)';
const IGNORE = ['.codeome/jobs/', '.codeome/worktrees/', '.codeome/plans/'];
const ENGINE_LABEL = { claude: 'Claude', codex: 'Codex', cross: 'the other engine' };

const sha = (s) => crypto.createHash('sha256').update(s).digest('hex');
const read = (p) => { try { return fs.readFileSync(p, 'utf8'); } catch { return null; } };

function parseFrontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!m) return { meta: {}, body: text };
  const meta = {};
  for (const line of m[1].split('\n')) {
    const i = line.indexOf(':');
    if (i > 0) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  return { meta, body: m[2] };
}

function roles() {
  const dir = path.join(KIT, 'roles');
  const footer = fs.readFileSync(path.join(dir, '_report.md'), 'utf8');
  return fs.readdirSync(dir).filter((f) => f.endsWith('.md') && !f.startsWith('_')).sort().map((f) => {
    const { meta, body } = parseFrontmatter(fs.readFileSync(path.join(dir, f), 'utf8'));
    return { ...meta, body: body.trim() + '\n' + footer };
  });
}

// Claude Code agent file: only the frontmatter keys Claude Code understands.
function agentFile(r) {
  const fm = ['---', `name: ${r.name}`, `description: ${r.description}`];
  if (r.tools) fm.push(`tools: ${r.tools}`);
  if (r.model) fm.push(`model: ${r.model}`);
  return fm.join('\n') + '\n---\n\n' + r.body;
}

function routingFile(list) {
  const rows = list.map((r) => `| \`${r.name}\` | ${ENGINE_LABEL[r.engine] || r.engine} | ${/Edit|Write/.test(r.tools || '') ? 'writes' : 'read-only'} | ${r.description} |`);
  return [
    '# Routing',
    '',
    'Generated by Codeome from the installed roles. Edit the Engine column to change a default for this project; Codeome will then leave this file alone on updates.',
    '',
    '| Role | Engine | Access | Use for |',
    '|---|---|---|---|',
    ...rows,
    '',
    'Engines:',
    '- **Claude** — Agent tool with `subagent_type` set to the role.',
    '- **Codex** — `.codeome/bin/codeome-agent codex --role <role> --title "…"` with the brief on stdin, run in the background. Sandboxed: no network, no SSH.',
    '- **the other engine** — reviewers run on whichever engine did not write the change.',
    '',
    'Override per task when it helps: a Codex role whose job needs the network or the HPC runs on Claude instead. If the user asks for a specific engine, use it.',
    ''
  ].join('\n');
}

function skillFiles() {
  const out = {};
  const base = path.join(KIT, 'skills');
  for (const skill of fs.readdirSync(base)) {
    const dir = path.join(base, skill);
    if (!fs.statSync(dir).isDirectory()) continue;
    for (const f of fs.readdirSync(dir)) out[`.claude/skills/${skill}/${f}`] = fs.readFileSync(path.join(dir, f), 'utf8');
  }
  return out;
}

function normalizeGroups(groups) {
  const valid = Object.keys(MANIFEST.groups);
  const want = new Set((groups || valid).filter((g) => valid.includes(g)));
  for (const [g, info] of Object.entries(MANIFEST.groups)) if (info.required) want.add(g);
  return valid.filter((g) => want.has(g));
}

// Everything the kit would write for these groups: { relPath: content }.
function plan(groups) {
  const chosen = roles().filter((r) => groups.includes(r.group));
  const files = { ...skillFiles() };
  for (const r of chosen) files[`.claude/agents/${r.name}.md`] = agentFile(r);
  files['.claude/skills/orchestrate/routing.md'] = routingFile(chosen);
  files['.codeome/bin/codeome-agent'] = fs.readFileSync(path.join(KIT, 'bin', 'codeome-agent'), 'utf8');
  return files;
}

function readState(project) {
  try { return JSON.parse(fs.readFileSync(path.join(project, '.codeome', 'kit.json'), 'utf8')); } catch { return null; }
}

function status(project) {
  const st = readState(project);
  const base = { latest: MANIFEST.version, groups: MANIFEST.groups, roles: roles().map((r) => ({ name: r.name, group: r.group, engine: r.engine, description: r.description })) };
  if (!st) return { ...base, installed: false };
  const modified = Object.entries(st.files || {}).filter(([rel, h]) => { const c = read(path.join(project, rel)); return c !== null && sha(c) !== h; }).map(([rel]) => rel);
  const missing = Object.keys(st.files || {}).filter((rel) => read(path.join(project, rel)) === null);
  return { ...base, installed: true, version: st.version, installedGroups: st.groups, outdated: st.version !== MANIFEST.version, modified, missing, installedAt: st.installedAt };
}

function mergeSettings(project) {
  const p = path.join(project, '.claude', 'settings.json');
  const raw = read(p);
  let s = {};
  if (raw !== null) { try { s = JSON.parse(raw); } catch { return { error: '.claude/settings.json is not valid JSON; hooks were not added.' }; } }
  s.hooks = s.hooks || {};
  const ours = (groups) => (groups || []).some((g) => (g.hooks || []).some((h) => String(h.command || '').includes('codeome-agent')));
  const add = (event, matcher) => {
    s.hooks[event] = s.hooks[event] || [];
    if (!ours(s.hooks[event])) s.hooks[event].push({ ...(matcher ? { matcher } : {}), hooks: [{ type: 'command', command: HOOK_CMD }] });
  };
  add('PreToolUse', 'Agent');
  add('SubagentStart');
  add('SubagentStop');
  s.permissions = s.permissions || {};
  s.permissions.allow = s.permissions.allow || [];
  if (!s.permissions.allow.includes(PERMISSION)) s.permissions.allow.push(PERMISSION);
  const out = JSON.stringify(s, null, 2) + '\n';
  if (out !== raw) { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, out); }
  return {};
}

function mergeGitignore(project) {
  const p = path.join(project, '.gitignore');
  const cur = read(p) || '';
  const have = new Set(cur.split('\n').map((l) => l.trim()));
  const add = IGNORE.filter((l) => !have.has(l));
  if (!add.length) return;
  fs.writeFileSync(p, cur + (cur && !cur.endsWith('\n') ? '\n' : '') + (cur ? '\n' : '') + '# Codeome agent jobs\n' + add.join('\n') + '\n');
}

// Install or update. Returns what happened to each file.
function install(project, opts = {}) {
  if (!project || !fs.existsSync(project)) throw new Error('Project folder not found: ' + project);
  const groups = normalizeGroups(opts.groups);
  const prev = readState(project) || { files: {} };
  const files = plan(groups);
  const r = { written: [], unchanged: [], skipped: [], removed: [], kept: [], groups };
  const record = {};

  for (const [rel, content] of Object.entries(files)) {
    const abs = path.join(project, rel);
    const cur = read(abs);
    const known = prev.files[rel];
    if (cur !== null && cur === content) { r.unchanged.push(rel); record[rel] = sha(content); continue; }
    // Edited by the user since we installed it, or a file we never wrote: leave it.
    if (cur !== null && (!known || sha(cur) !== known)) { r.skipped.push(rel); if (known) record[rel] = known; continue; }
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content);
    if (rel.startsWith('.codeome/bin/')) fs.chmodSync(abs, 0o755);
    r.written.push(rel);
    record[rel] = sha(content);
  }
  // Roles from groups that were deselected, or dropped from the kit.
  for (const [rel, h] of Object.entries(prev.files)) {
    if (rel in files) continue;
    const cur = read(path.join(project, rel));
    if (cur === null) continue;
    if (sha(cur) === h) { fs.unlinkSync(path.join(project, rel)); r.removed.push(rel); } else r.kept.push(rel);
  }

  const st = mergeSettings(project);
  if (st.error) r.warning = st.error;
  mergeGitignore(project);
  fs.mkdirSync(path.join(project, '.codeome'), { recursive: true });
  fs.writeFileSync(path.join(project, '.codeome', 'kit.json'), JSON.stringify({ version: MANIFEST.version, groups, installedAt: new Date().toISOString(), files: record }, null, 2) + '\n');
  return r;
}

module.exports = { install, status, plan, roles, parseFrontmatter, MANIFEST, HOOK_CMD };
