const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { pointer, DARK_CSS } = require('../main/gdoc');

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'codeome-gdoc-'));
const file = (name, content) => { const p = path.join(tmp, name); fs.writeFileSync(p, typeof content === 'string' ? content : JSON.stringify(content)); return p; };

test('pointer: reads the document id and builds the editor address for each kind', () => {
  const d = { '': 'WARNING! DO NOT EDIT THIS FILE!', doc_id: '1Ab-c_D9', resource_key: '', email: 'me@example.org' };
  assert.deepStrictEqual(pointer(file('Notes.gdoc', d)), { docId: '1Ab-c_D9', url: 'https://docs.google.com/document/d/1Ab-c_D9/edit', email: 'me@example.org' });
  assert.strictEqual(pointer(file('Counts.gsheet', d)).url, 'https://docs.google.com/spreadsheets/d/1Ab-c_D9/edit');
  assert.strictEqual(pointer(file('Talk.GSLIDES', d)).url, 'https://docs.google.com/presentation/d/1Ab-c_D9/edit');
});

test('pointer: passes the resource key on', () => {
  assert.strictEqual(pointer(file('Old.gdoc', { doc_id: 'abc', resource_key: '0-x/y' })).url, 'https://docs.google.com/document/d/abc/edit?resourcekey=0-x%2Fy');
});

test('pointer: refuses other files, unreadable ones and ids that are not ids', () => {
  assert.throws(() => pointer(file('notes.txt', {})), /Not a Google/);
  assert.throws(() => pointer(file('Broken.gdoc', 'not json')), /Could not read/);
  assert.throws(() => pointer(path.join(tmp, 'Missing.gdoc')), /Could not read/);
  assert.throws(() => pointer(file('Empty.gdoc', {})), /no document id/);
  assert.throws(() => pointer(file('Odd.gdoc', { doc_id: 'a/../b' })), /no document id/);
});

test('dark colours: the page is flipped and its pictures flipped back', () => {
  assert.match(DARK_CSS, /body\{filter:invert\(1\)/);
  assert.match(DARK_CSS, /mix-blend-mode:lighten/);
  assert.match(DARK_CSS, /img,video/);
});
